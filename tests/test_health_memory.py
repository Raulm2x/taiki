"""Health de memoria: integridad, cola, presupuesto y artefactos generados."""

from __future__ import annotations

from datetime import datetime, timedelta
from pathlib import Path

from mcp_layer import handlers
from ticketlib import db
from ticketlib.memory import add_memory
from tests.support import Harness

_META = {"sessionId": "ses_health_memory"}


def _ago(days: int) -> str:
    return (
        datetime.now().astimezone() - timedelta(days=days)
    ).isoformat(timespec="seconds")


def _brief(root: Path) -> None:
    folder = root / ".taiki" / "generated"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "brief.md").write_text("generated by taiki; do not edit\n", encoding="utf-8")


def run(h: Harness) -> None:
    conn = h.conn
    active = add_memory(
        conn,
        title="Activa health",
        content="Contenido activo.",
        key="health-active",
        source="user",
    )
    add_memory(
        conn,
        title="Stale health",
        content="Caducada.",
        key="health-stale",
        source="user",
    )
    conn.execute(
        "UPDATE memories SET status = 'stale' WHERE \"key\" = 'health-stale'"
    )
    proposal = add_memory(
        conn,
        title="Propuesta health",
        content="Pendiente.",
        kind="decision",
        key="health-proposal",
        source="agent",
        evidence=[{"kind": "ticket", "ref": "T-0048.03"}],
    )
    conn.execute(
        "UPDATE memories SET created_at = ? WHERE code = ?",
        (_ago(10), proposal["code"]),
    )
    conn.commit()

    root = h.tmp / "health-root"
    _brief(root)
    original = handlers._project_root
    handlers._project_root = lambda: root
    try:
        health = handlers.call_tool("health", {"servers": False}, meta=_META)
        memory = health["memory"]
        h.eq(
            set(memory),
            {
                "enabled",
                "db_ok",
                "entries",
                "pending",
                "stale",
                "budget",
                "generated_synced",
                "issues",
            },
            "health expone la sección memory estable",
        )
        h.ok(
            memory["enabled"]
            and memory["db_ok"]
            and memory["entries"] >= 3
            and memory["pending"] == 1
            and memory["stale"] == 1,
            "health cuenta entradas, propuestas y stale",
        )
        h.ok(
            {"project", "user"} <= set(memory["budget"]),
            "health incluye presupuesto por scope",
        )
        h.ok(memory["generated_synced"], "health detecta artefactos generados")
        h.ok(
            any("7 días" in item for item in memory["issues"])
            and any("stale" in item for item in memory["issues"]),
            "health avisa de propuestas antiguas y stale",
        )
        h.ok(health["ok"], "los avisos de memoria no bloquean health")

        conn.execute(
            "UPDATE memories SET content = ? WHERE code = ?",
            ("x" * 3500, active["code"]),
        )
        conn.commit()
        over = handlers.call_tool("health", {"servers": False}, meta=_META)
        h.ok(
            over["memory"]["budget"]["project"]["chars_to_free"] > 0
            and any("presupuesto" in item for item in over["memory"]["issues"])
            and over["ok"],
            "el presupuesto excedido avisa sin bloquear",
        )

        no_artifacts = h.tmp / "sin-artefactos"
        no_artifacts.mkdir()
        handlers._project_root = lambda: no_artifacts
        missing = handlers.call_tool("health", {"servers": False}, meta=_META)
        h.ok(
            not missing["memory"]["generated_synced"]
            and any("brief.md" in item for item in missing["memory"]["issues"]),
            "health detecta artefactos generados ausentes",
        )
    finally:
        handlers._project_root = original

    broken_path = h.tmp / "broken-health.db"
    broken = db.connect(broken_path)
    try:
        broken.execute("DROP TABLE memories_fts")
        broken.commit()
    finally:
        broken.close()
    handlers._project_root = lambda: root
    try:
        with h.env(TAIKI_DB=str(broken_path)):
            broken_health = handlers.call_tool(
                "health", {"servers": False}, meta=_META
            )
        h.ok(
            broken_health["memory"]["db_ok"] is False
            and any(
                item.startswith("error:") for item in broken_health["memory"]["issues"]
            )
            and not broken_health["ok"],
            "una tabla/FTS rota bloquea health como issue grave",
        )
    finally:
        handlers._project_root = original
