"""Sincronización del brief generado con la configuración de OpenCode."""

from __future__ import annotations

import json
from pathlib import Path

from ticketlib.memory import add_memory
from ticketlib.memory.sync import (
    BRIEF_INSTRUCTION,
    install_opencode_memory,
    sync_generated,
    uninstall_opencode_memory,
)
from tests.support import Harness


def _config(root: Path, instructions: list[str] | None = None) -> Path:
    data: dict[str, object] = {
        "$schema": "https://opencode.ai/config.json",
        "theme": "noctalia",
        "mcp": {"servers": {}},
    }
    if instructions is not None:
        data["instructions"] = instructions
    path = root / "opencode.json"
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    return path


def _load(path: Path) -> dict[str, object]:
    return json.loads(path.read_text(encoding="utf-8"))


def run(h: Harness) -> None:
    root = Path(h.tmp) / "proyecto"
    root.mkdir()
    add_memory(
        h.conn,
        title="Rama de integración",
        content="develop integra con --ff-only.",
        kind="convention",
        key="rama-integracion",
        scope="project",
        source="user",
    )
    config = {"memory": {"enabled": True}}

    synced = sync_generated(root, h.conn, config)
    brief = Path(synced["brief_path"])
    text = brief.read_text(encoding="utf-8")
    h.ok(
        brief == root / ".taiki" / "generated" / "brief.md"
        and "generated by taiki" in text
        and "Rama de integración" in text,
        "sync_generated escribe el brief con cabecera y memorias",
    )
    h.ok(
        synced["chars"] > 0 and synced["version"] == 1,
        "sync_generated devuelve chars y versión",
    )
    gitignore = root / ".taiki" / ".gitignore"
    h.ok(
        "generated/" in gitignore.read_text(encoding="utf-8").splitlines(),
        "el .gitignore del workspace ignora generated/",
    )

    sync_generated(root, h.conn, config)
    h.eq(
        gitignore.read_text(encoding="utf-8").splitlines().count("generated/"),
        1,
        "sync repetido no duplica generated/",
    )

    path = _config(root, ["./AGENTS.md"])
    before = _load(path)
    first = install_opencode_memory(root)
    after = _load(path)
    h.ok(
        first["added"] is True
        and after["instructions"] == ["./AGENTS.md", BRIEF_INSTRUCTION]
        and list(after) == list(before),
        "install añade instructions al final y preserva claves y orden",
    )
    h.ok(
        BRIEF_INSTRUCTION in after["instructions"]
        and not any(item.startswith("/") for item in after["instructions"]),
        "instructions usa una ruta relativa al proyecto",
    )
    second = install_opencode_memory(root)
    h.ok(
        second["added"] is False
        and _load(path)["instructions"] == after["instructions"],
        "install es idempotente",
    )

    removed = uninstall_opencode_memory(root)
    cleaned = _load(path)
    h.ok(
        removed == path
        and cleaned["instructions"] == ["./AGENTS.md"]
        and cleaned["theme"] == "noctalia"
        and "mcp" in cleaned,
        "uninstall retira solo la entrada y conserva el resto",
    )
    h.eq(
        uninstall_opencode_memory(root),
        None,
        "uninstall repetido no hace nada",
    )

    nested = Path(h.tmp) / "anidado"
    (nested / ".opencode").mkdir(parents=True)
    (nested / ".opencode" / "opencode.json").write_text("{}", encoding="utf-8")
    install_opencode_memory(nested)
    h.eq(
        _load(nested / ".opencode" / "opencode.json")["instructions"],
        [BRIEF_INSTRUCTION],
        "install usa .opencode/opencode.json cuando existe",
    )

    repo_config = _load(Path(__file__).resolve().parent.parent / ".taiki" / "config.json")
    h.ok(
        repo_config["memory"]["enabled"] is True
        and repo_config["memory"]["brief_budget_chars"] == 4500,
        "el config del proyecto declara el bloque memory",
    )
